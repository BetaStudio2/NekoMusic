    /**
     * 将简体中文转换为繁体中文
     * @param text 输入文本
     * @return 转换后的繁体中文
     */
    public static String toTraditional(String text) {
        if (text == null || text.isEmpty()) {
            return text;
        }
        
        StringBuilder result = new StringBuilder();
        for (char c : text.toCharArray()) {
            result.append(SIMPLIFIED_TO_TRADITIONAL.getOrDefault(c, c));
        }
        return result.toString();
    }
    
    /**
     * 将繁体中文转换为简体中文
     * @param text 输入文本
     * @return 转换后的简体中文
     */
    public static String toSimplified(String text) {
        if (text == null || text.isEmpty()) {
            return text;
        }
        
        StringBuilder result = new StringBuilder();
        for (char c : text.toCharArray()) {
            result.append(TRADITIONAL_TO_SIMPLIFIED.getOrDefault(c, c));
        }
        return result.toString();
    }
    
    /**
     * 生成搜索用的繁简体版本
     * @param query 搜索关键词
     * @return 包含简体和繁体的数组
     */
    public static String[] getSearchVariants(String query) {
        if (query == null || query.isEmpty()) {
            return new String[]{query};
        }
        
        String simplified = toSimplified(query);
        String traditional = toTraditional(query);
        
        // 如果转换后与原文本相同，只返回一个版本
        if (simplified.equals(traditional)) {
            return new String[]{simplified};
        }
        
        // 返回简体和繁体两个版本
        return new String[]{simplified, traditional};
    }
